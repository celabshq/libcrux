/// Reverses to fiat's little-endian byte order and outputs in
/// standard domain. Does NOT validate that the scalar is reduced.
const fn fpraw_from_be_bytes(be: &[u8; FP_NUM_BYTES]) -> FpRaw {
    let mut le = [0u8; FP_NUM_BYTES];
    let mut i = 0;
    while i < FP_NUM_BYTES {
        le[i] = be[47 - i];
        i += 1;
    }
    let mut raw = FpRaw::new();
    fp_from_bytes(&mut raw, &le);
    raw
}

/// Reverses to fiat's little-endian byte order and outputs in
/// Montgomery domain. Does NOT validate that the scalar is reduced.
pub(crate) const fn fp_from_be_bytes(be: &[u8; FP_NUM_BYTES]) -> Fp {
    let mut out = Fp::new();
    let out_raw = fpraw_from_be_bytes(be);
    fp_to_montgomery(&mut out, &out_raw);
    out
}

pub(crate) const NIST_P384_A: Fp = fp_from_be_bytes(&NIST_P384_A_BE_BYTES);
pub(crate) const NIST_P384_B: Fp = fp_from_be_bytes(&NIST_P384_B_BE_BYTES);
pub(crate) const NIST_P384_GX: Fp = fp_from_be_bytes(&NIST_P384_GX_BE_BYTES);
pub(crate) const NIST_P384_GY: Fp = fp_from_be_bytes(&NIST_P384_GY_BE_BYTES);

/// One in P-384's base field, in Montgomery form.
pub(crate) const FP_ONE: Fp = {
    let mut out = Fp::new();
    fiat_p384_set_one(&mut out);
    out
};

/// Zero in P-384's base field, in Montgomery form.
pub(crate) const FP_ZERO: Fp = Fp([0u64; FP_NUM_LIMBS]);

