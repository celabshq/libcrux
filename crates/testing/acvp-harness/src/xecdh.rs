//! XECDH (RFC 7748) on Curve25519: key generation, public key validation and shared secret
//! computation.

use libcrux_curve25519::{DK_LEN, EK_LEN, SS_LEN};
use libcrux_kats::acvp::{
    schema_common::Prompts,
    xecdh::schema::{
        KeyGenPromptTestGroup, KeyGenResult, KeyVerPromptTestGroup, KeyVerResult,
        SscPromptTestGroup, SscResult,
    },
};
use rand::RngExt;
use serde_json::Value;

use crate::{not_implemented, parse, respond_implemented};

/// Whether libcrux implements XECDH on `curve`.
fn implemented(curve: &str) -> bool {
    match curve {
        "Curve25519" => true,
        "Curve448" => false,
        c => panic!("unexpected curve {c}"),
    }
}

/// A key pair as generated by `libcrux_curve25519`: a random clamped scalar and its public key.
fn generate_key_pair() -> ([u8; DK_LEN], [u8; EK_LEN]) {
    let mut sk: [u8; DK_LEN] = rand::rng().random();
    libcrux_curve25519::clamp(&mut sk);
    let mut pk = [0u8; EK_LEN];
    libcrux_curve25519::secret_to_public(&mut pk, &sk);
    (sk, pk)
}

pub(crate) fn keygen(prompt: Value) -> Value {
    let prompts: Prompts<KeyGenPromptTestGroup> = parse(prompt);

    respond_implemented(&prompts, |g, t| {
        if !implemented(&g.curve) {
            return not_implemented(&g.curve);
        }
        let (sk, pk) = generate_key_pair();
        Some(KeyGenResult {
            tcId: t.tcId,
            privateKey: sk.to_vec(),
            publicKey: pk.to_vec(),
        })
    })
}

/// For X25519, public key validation only checks the length (RFC 7748, Section 5).
pub(crate) fn keyver(prompt: Value) -> Value {
    let prompts: Prompts<KeyVerPromptTestGroup> = parse(prompt);

    respond_implemented(&prompts, |g, t| {
        if !implemented(&g.curve) {
            return not_implemented(&g.curve);
        }
        Some(KeyVerResult {
            tcId: t.tcId,
            testPassed: <&[u8; EK_LEN]>::try_from(t.publicKey.as_slice()).is_ok(),
        })
    })
}

pub(crate) fn ssc(prompt: Value) -> Value {
    let prompts: Prompts<SscPromptTestGroup> = parse(prompt);

    respond_implemented(&prompts, |g, t| {
        if !implemented(&g.curve) {
            return not_implemented(&g.curve);
        }
        assert_eq!(g.testType, "AFT");
        let (sk, pk) = generate_key_pair();
        let server: &[u8; EK_LEN] = t
            .publicServer
            .as_slice()
            .try_into()
            .expect("invalid server public key");
        let mut z = [0u8; SS_LEN];
        assert!(
            libcrux_curve25519::ecdh(&mut z, server, &sk).is_ok(),
            "ECDH failed"
        );
        Some(SscResult {
            tcId: t.tcId,
            publicIut: pk.to_vec(),
            z: z.to_vec(),
        })
    })
}
